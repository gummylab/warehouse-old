import { after } from 'next/server'
import { NextResponse } from 'next/server'

import { Worker } from 'worker_threads'

import { itemExists, saveImageOriginal, writeImageVariants } from '@/lib/db/order-images'
import { authenticateOrderImageRequest } from '@/lib/liff/order-session'
import { isAcceptedImageType, MAX_FILE_BYTES } from '@/lib/order-images/upload'
import sharp from 'sharp'

// One file per request; the form loops over a multi-file selection so a
// single failure can be reported without losing the other uploads. The
// size and type caps live in lib/order-images/upload.ts, shared with the
// client-side pre-check.
//
// Heavy variant generation (sharp resize) is deferred to `after()` so the
// response returns as soon as the original is saved. The file-serving route
// falls back to the original when web/thumb are not ready yet.
//
// RouteContext<'/api/liff/order-images/items/[id]/images'> is generated by
// `next typegen`, so the param name is checked against the actual folder.
export async function POST(
  request: Request,
  { params }: RouteContext<'/api/liff/order-images/items/[id]/images'>,
) {
  const auth = await authenticateOrderImageRequest(request)
  if (!auth.ok) {
    return NextResponse.json({ error: 'unauthorized' }, { status: auth.status })
  }

  const { id: itemId } = await params
  if (!itemExists(itemId)) {
    return NextResponse.json({ error: 'item-not-found' }, { status: 404 })
  }

  const form = await request.formData().catch(() => null)
  const file = form?.get('file')
  if (!(file instanceof File) || file.size === 0) {
    return NextResponse.json({ error: 'file-missing' }, { status: 400 })
  }
  if (file.size > MAX_FILE_BYTES) {
    return NextResponse.json({ error: 'file-too-large' }, { status: 413 })
  }
  if (!isAcceptedImageType(file.type)) {
    return NextResponse.json({ error: 'unsupported-type' }, { status: 400 })
  }

  const buffer = Buffer.from(await file.arrayBuffer())

  // Lightweight format validation (sharp metadata read) — fast enough to
  // keep in the request path so we can return 400 for bad images.
  const meta = await sharp(buffer).metadata().catch(() => null)
  if (
    !meta?.format ||
    !['jpeg', 'png', 'webp'].includes(meta.format) ||
    !meta.width ||
    !meta.height
  ) {
    return NextResponse.json({ error: 'unsupported-type' }, { status: 400 })
  }

  // Save original + create DB record (fast, no sharp resize).
  const { image, key } = saveImageOriginal({
    itemId,
    package: null,
    fileName: file.name,
    mimeType: file.type,
    fileSize: file.size,
    createdBy: auth.createdBy,
    buffer,
  })

  // Defer heavy variant generation to a worker thread (after the response).
  after(async () => {
    try {
      const worker = new Worker(new URL('../../../../../../../lib/order-images/variant-worker.ts', import.meta.url))
      const variants = await new Promise<{ web: Buffer; thumb: Buffer }>((resolve, reject) => {
        worker.on('message', (msg: { ok: boolean; web?: ArrayBuffer; thumb?: ArrayBuffer; error?: string }) => {
          worker.terminate()
          if (msg.ok && msg.web && msg.thumb) {
            resolve({ web: Buffer.from(msg.web), thumb: Buffer.from(msg.thumb) })
          } else {
            reject(new Error(msg.error || 'variant generation failed'))
          }
        })
        worker.on('error', (err) => { worker.terminate(); reject(err) })
        worker.on('exit', (code) => { if (code !== 0) reject(new Error(`worker exited with code ${code}`)) })
        // Send the buffer to the worker (structured clone, no transfer).
        worker.postMessage({ buffer })
      })
      writeImageVariants(key, variants.web, variants.thumb)
    } catch (error) {
      // Variant generation failed (e.g. corrupt pixels). The file-serving
      // route falls back to the original, so the upload still succeeds.
      console.error('[after] variant generation failed:', error)
    }
  })

  return NextResponse.json({ image }, { status: 201 })
}
