import { after } from 'next/server'
import { NextResponse } from 'next/server'

import { safeRevalidateTag } from '@/lib/cache/revalidate'
import { itemExists, saveImageOriginal } from '@/lib/db/order-images'
import { authenticateFormRequest } from '@/lib/liff/order-session'
import { buildImageVariants } from '@/lib/order-images/optimize'
import { isAcceptedImageType, MAX_FILE_BYTES, validateImageMagicBytes } from '@/lib/order-images/upload'

// One file per request; the form loops over a multi-file selection so a
// single failure can be reported without losing the other uploads. The
// size and type caps live in lib/order-images/upload.ts, shared with the
// client-side pre-check.
//
// Heavy variant generation (sharp resize) is deferred to `after()` so the
// response returns as soon as the original is saved. The file-serving route
// falls back to the original when web/thumb are not ready yet.
//
// RouteContext<'/api/liff/order-images/items/[id]/images'> is generated by
// `next typegen`, so the param name is checked against the actual folder.
export async function POST(
  request: Request,
  { params }: RouteContext<'/api/liff/order-images/items/[id]/images'>,
) {
  const auth = await authenticateFormRequest(request, 'order-image')
  if (!auth.ok) {
    return NextResponse.json({ error: 'unauthorized' }, { status: auth.status })
  }

  const { id: itemId } = await params
  if (!itemExists(itemId)) {
    return NextResponse.json({ error: 'item-not-found' }, { status: 404 })
  }

  const form = await request.formData().catch(() => null)
  const file = form?.get('file')
  if (!(file instanceof File) || file.size === 0) {
    return NextResponse.json({ error: 'file-missing' }, { status: 400 })
  }
  if (file.size > MAX_FILE_BYTES) {
    return NextResponse.json({ error: 'file-too-large' }, { status: 413 })
  }
  if (!isAcceptedImageType(file.type)) {
    return NextResponse.json({ error: 'unsupported-type' }, { status: 400 })
  }

  const buffer = Buffer.from(await file.arrayBuffer())

  // Fast format validation via magic bytes — avoids reading the entire
  // buffer through sharp (which is slow for large files). Corrupt images
  // with valid magic bytes are caught later during variant generation.
  if (!validateImageMagicBytes(buffer)) {
    return NextResponse.json({ error: 'unsupported-type' }, { status: 400 })
  }

  // Save original + create DB record (fast, no sharp resize).
  const { image, key } = saveImageOriginal({
    itemId,
    package: null,
    fileName: file.name,
    mimeType: file.type,
    fileSize: file.size,
    createdBy: auth.createdBy,
    buffer,
  })

  // The admin overview counts photos, so a new one has to expire the cached
  // numbers; this route is called from the phone, where no page revalidation
  // would run on its own.
  safeRevalidateTag('orders')

  // Defer heavy variant generation to after the response.
  after(async () => {
    try {
      const variants = await buildImageVariants(buffer)
      // Write variants to disk (file-serving route falls back to original
      // if these are missing, so a failure here is non-fatal).
      const { derivativePath, ensureDirForFile } = await import('@/lib/order-images/storage')
      const webPath = derivativePath(key, 'web')
      const thumbPath = derivativePath(key, 'thumb')
      ensureDirForFile(webPath)
      ensureDirForFile(thumbPath)
      const { writeFile } = await import('node:fs/promises')
      await writeFile(webPath, variants.web)
      await writeFile(thumbPath, variants.thumb)
    } catch (error) {
      // Variant generation failed (e.g. corrupt pixels). The file-serving
      // route falls back to the original, so the upload still succeeds.
      console.error('[after] variant generation failed:', error)
    }
  })

  return NextResponse.json({ image }, { status: 201 })
}
