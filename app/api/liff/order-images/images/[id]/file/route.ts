import { readFile } from 'node:fs/promises'

import { NextResponse } from 'next/server'

import { getImageFile } from '@/lib/db/order-images'
import { authenticateOrderImageRequest } from '@/lib/liff/order-session'
import {
  derivativePath,
  isInsideRoot,
  originalPath,
  type ImageSize,
} from '@/lib/order-images/storage'

type RequestedSize = ImageSize | 'original'

// Serves the stored bytes behind <img src=".../file">. The session cookie
// (sent automatically by the browser) is what authenticates these requests
// — an img tag cannot carry headers.
//
// ?size=web (the default) and ?size=thumb read the derivative; ?size=original
// reads the uploaded file. A missing derivative falls back to the original, so
// a row whose generation failed still shows its photo.
//
// RouteContext<'/api/liff/order-images/images/[id]/file'> is generated by
// `next typegen`, so the param name is checked against the actual folder.
export async function GET(
  request: Request,
  { params }: RouteContext<'/api/liff/order-images/images/[id]/file'>,
) {
  const auth = await authenticateOrderImageRequest(request)
  if (!auth.ok) {
    return NextResponse.json({ error: 'unauthorized' }, { status: auth.status })
  }

  const { id } = await params
  const file = getImageFile(id)
  if (!file) {
    return NextResponse.json({ error: 'image-not-found' }, { status: 404 })
  }

  const requested = new URL(request.url).searchParams.get('size')
  const size: RequestedSize =
    requested === 'thumb' || requested === 'original' ? requested : 'web'

  const original = originalPath(file.storageKey)
  const absolute = size === 'original' ? original : derivativePath(file.storageKey, size)
  // A storage_key that escapes the storage root must never be read, even
  // though only the server can write that column. Both paths are checked
  // because a missing derivative falls back to the original.
  if (!isInsideRoot(absolute) || !isInsideRoot(original)) {
    return NextResponse.json({ error: 'image-not-found' }, { status: 404 })
  }

  let bytes: Buffer
  let contentType = size === 'original' ? file.mimeType : 'image/webp'
  try {
    bytes = await readFile(absolute)
  } catch {
    if (size === 'original') {
      // Row exists but the file is gone (manual delete, failed copy): the
      // client shows a broken thumbnail rather than a 500 page.
      return NextResponse.json({ error: 'file-missing' }, { status: 404 })
    }
    try {
      bytes = await readFile(original)
      contentType = file.mimeType
    } catch {
      return NextResponse.json({ error: 'file-missing' }, { status: 404 })
    }
  }

  // The bytes are copied into a fresh Uint8Array because BodyInit does not
  // accept a Buffer's ArrayBufferLike view. The copy is bounded by the 10 MB
  // upload limit and happens after the file is already in memory, so it is
  // not worth streaming the file to avoid it.
  return new NextResponse(new Uint8Array(bytes), {
    headers: {
      'Content-Type': contentType ?? 'application/octet-stream',
      // The stored bytes come from a phone upload and the Content-Type is
      // whatever the client claimed, so the browser must not be allowed to
      // sniff its way to a different type (an HTML body served as an image
      // would run as a script on this origin).
      'X-Content-Type-Options': 'nosniff',
      // private: the bytes are auth-gated, so shared caches must not keep
      // them. immutable: a given image id never changes content, and a
      // replaced photo always gets a fresh id.
      'Cache-Control': 'private, max-age=31536000, immutable',
    },
  })
}
