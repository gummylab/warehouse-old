import { io } from 'next/cache'
import type { Metadata } from 'next'

import { FormPage } from '@/components/layout/form-page'
import { ButtonLink } from '@/components/ui/button'
import { getItemDetail } from '@/lib/db/order-images'

import { FormNavbar } from '../../../../form-navbar'
import { ItemImages } from './item-images'

// The LIFF layout gate withholds children until the LINE session resolves,
// so the dev server's instant-navigation simulation never renders this
// segment and reports it as "dropped". The masking is the design, not a
// defect — this opts the route out of that validation (see /liff/forms).
export const instant = false

// Dynamic route: the item number is only known at request time, and /liff
// pages carry no header label, so a static title serves metadata.
export const metadata: Metadata = {
  title: 'รูปภาพไอเท็ม',
}

// PageProps<'/liff/forms/order-image/items/[itemId]'> is generated by
// `next typegen` (see the typecheck script). It types the params against
// the actual route, so a renamed folder shows up as a type error here
// instead of as an undefined value at runtime.
export default async function ItemImagesPage(props: PageProps<'/liff/forms/order-image/items/[itemId]'>) {
  const { itemId } = await props.params

  // io() keeps the synchronous DB read out of the static shell; during a
  // real request it resolves immediately.
  await io()
  const detail = getItemDetail(itemId)

  if (!detail) {
    return (
      <FormPage header={<FormNavbar title="ไม่พบไอเท็มนี้" />}>
        <p className="text-sm text-muted-foreground">
          ไอเท็มอาจถูกลบไปแล้ว หรือลิงก์ไม่ถูกต้อง
        </p>
        <ButtonLink
          variant="outline"
          href="/liff/forms/order-image"
          className="self-start">
          กลับไปหน้าแบบฟอร์ม
        </ButtonLink>
      </FormPage>
    )
  }

  return <ItemImages initialDetail={detail} />
}
